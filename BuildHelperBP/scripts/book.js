/** パッチノートの章を組み立てる（PATCH_NOTES から自動生成する）。 */
export function patchNotesBody() {
  const blocks = PATCH_NOTES.map((note) => {
    const lines = [`§l§ev${note.version}§r §7（${note.date}）§r`];
    for (const change of note.changes) lines.push(`　・${change}`);
    return lines.join("\n");
  });
  return blocks.join("\n\n");
}

